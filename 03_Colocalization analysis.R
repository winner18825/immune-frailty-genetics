# =============================================================================
# Colocalization analysis for MR-positive cell-gene pairs
# =============================================================================
# This script extracts original eQTL data for MR-positive cell-gene pairs,
# compares each pair with all nine GWAS traits, and runs coloc.abf.
# Depressive_symptoms and Reaction_time are quantitative traits; the remaining
# traits are treated as case-control traits.
# =============================================================================

source("config.R")
library(data.table)
library(coloc)

# Input and output locations
POSITIVE_RESULTS_FILE <- file.path(RESULTS_DIR, "mr", "MR_significant_results.txt")
EQTL_DIR <- DATA_DIR
OUTCOME_DIR <- DATA_DIR
RESULTS_COLOC_DIR <- file.path(RESULTS_DIR, "coloc")
dir.create(RESULTS_COLOC_DIR, recursive = TRUE, showWarnings = FALSE)

# Coloc prior probabilities
P1 <- 1e-4
P2 <- 1e-4
P12 <- 1e-5
PPH4_THRESHOLD <- 0.90

# Case fraction required by coloc for case-control traits.
CASE_FRACTION <- c(
  Exhaustion = 0.119,
  Low_Grip_strength = 0.138,
  Low_Physical_activity = 0.085,
  Slow_Walking_speed = 0.076,
  Social_interaction_and_isolation = 0.180,
  Trouble_falling_asleep = 0.760,
  Weight_loss = 0.153
)

outcome_type <- setNames(rep("cc", length(all_traits)), all_traits)
outcome_type[c("Depressive_symptoms", "Reaction_time")] <- "quant"

# Read MR-positive results and keep significant IVW or Wald-ratio results.
mr <- fread(POSITIVE_RESULTS_FILE, sep = "\t")

# The exposure identifier generated by the MR script is cell:gene.
pairs <- unique(mr[, {
  x <- strsplit(as.character(exposure), ":", fixed = TRUE)[[1]]
  if (length(x) >= 2) list(cell = x[1], gene = paste(x[-1], collapse = ":"))
  else list(cell = NA_character_, gene = NA_character_)
}, by = exposure])
pairs <- pairs[!is.na(cell) & !is.na(gene) & nzchar(cell) & nzchar(gene)]
pairs <- pairs[rep(seq_len(nrow(pairs)), each = length(all_traits))]
pairs[, trait := rep(all_traits, times = nrow(pairs) / length(all_traits))]

# Extract one gene from the original eQTL table.
read_eqtl <- function(cell_id, gene_id) {
  path <- file.path(EQTL_DIR, paste0(cell_id, "_eqtl_table.txt.gz"))
  if (!file.exists(path)) path <- file.path(EQTL_DIR, paste0(cell_id, "_eqtl_table.txt"))
  if (!file.exists(path)) stop("eQTL file not found: ", cell_id)
  x <- fread(path, sep = "\t")
  required <- c("GENE", "RSID", "beta", "se", "A2", "A1",
                "A2_FREQ_ONEK1K", "P_VALUE", "N", "CHR", "POS")
  stopifnot(all(required %in% names(x)))
  x <- x[GENE == gene_id]
  x <- x[, .(SNP = RSID, beta = beta, se = se,
             eaf = A2_FREQ_ONEK1K, pval = P_VALUE, N = N)]
  x[, varbeta := se^2]
  x[, MAF := pmin(eaf, 1 - eaf)]
  x <- x[!duplicated(SNP) & is.finite(beta) & is.finite(se) & se > 0 &
           is.finite(pval) & pval >= 0 & pval <= 1]
  x
}

# Read one standardized outcome GWAS file.
read_outcome <- function(trait_id) {
  path <- file.path(OUTCOME_DIR, paste0(trait_id, ".txt"))
  if (!file.exists(path)) stop("Outcome file not found: ", path)
  x <- fread(path, sep = "\t")
  required <- c("SNP", "chr", "pos", "effect_allele", "other_allele",
                "eaf", "beta", "se", "pval", "N")
  stopifnot(all(required %in% names(x)))
  x <- x[, .(SNP, beta, se, eaf, pval, N)]
  x[, varbeta := se^2]
  x[, MAF := pmin(eaf, 1 - eaf)]
  x <- x[!duplicated(SNP) & is.finite(beta) & is.finite(se) & se > 0 &
           is.finite(pval) & pval >= 0 & pval <= 1]
  x
}

run_coloc <- function(cell_id, gene_id, trait_id) {
  message("Running: ", cell_id, ":", gene_id, " -> ", trait_id)
  qtl <- read_eqtl(cell_id, gene_id)
  gwas <- read_outcome(trait_id)
  common <- intersect(qtl$SNP, gwas$SNP)
  if (length(common) < 2) return(NULL)
  qtl <- qtl[match(common, SNP)]
  gwas <- gwas[match(common, SNP)]
  
  d1 <- list(snp = qtl$SNP, beta = qtl$beta, varbeta = qtl$varbeta,
             N = median(qtl$N, na.rm = TRUE), MAF = qtl$MAF,
             pvalues = qtl$pval, type = "quant")
  d2 <- list(snp = gwas$SNP, beta = gwas$beta, varbeta = gwas$varbeta,
             N = median(gwas$N, na.rm = TRUE), MAF = gwas$MAF,
             pvalues = gwas$pval, type = outcome_type[[trait_id]])
  if (d2$type == "cc") d2$s <- CASE_FRACTION[[trait_id]]
  
  fit <- coloc.abf(d1, d2, p1 = P1, p2 = P2, p12 = P12)
  tag <- paste(cell_id, gene_id, trait_id, sep = "__")
  summary <- as.data.table(as.list(fit$summary))
  summary[, `:=`(cell = cell_id, gene = gene_id, trait = trait_id,
                 outcome_type = d2$type, shared_snps = length(common))]
  fwrite(summary, file.path(RESULTS_COLOC_DIR, paste0(tag, ".summary.tsv")), sep = "\t")
  fwrite(as.data.table(fit$results), file.path(RESULTS_COLOC_DIR, paste0(tag, ".snp.tsv")), sep = "\t")
  summary
}

results <- list()
errors <- list()
for (i in seq_len(nrow(pairs))) {
  z <- pairs[i]
  ans <- tryCatch(run_coloc(z$cell, z$gene, z$trait), error = function(e) {
    errors[[length(errors) + 1L]] <<- data.table(
      cell = z$cell, gene = z$gene, trait = z$trait, error = conditionMessage(e))
    NULL
  })
  if (!is.null(ans)) results[[length(results) + 1L]] <- ans
}
if (length(results)) fwrite(rbindlist(results, fill = TRUE),
                            file.path(RESULTS_COLOC_DIR, "coloc_summary_all.tsv"), sep = "\t")
if (length(errors)) fwrite(rbindlist(errors, fill = TRUE),
                           file.path(RESULTS_COLOC_DIR, "coloc_errors.tsv"), sep = "\t")
message("Colocalization analysis complete.")
